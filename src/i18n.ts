export function relativeTime(at:number,now=Date.now(),locale:UiLanguage=language){
 const seconds=Math.max(0,(now-at)/1000);
 if(seconds<60)return translate(locale,'刚刚');
 if(seconds<3600)return locale==='en'?Math.floor(seconds/60)+' min ago':Math.floor(seconds/60)+' 分钟前';
 if(seconds<86400)return locale==='en'?Math.floor(seconds/3600)+' hr ago':Math.floor(seconds/3600)+' 小时前';
 return new Date(at).toLocaleDateString(locale,{month:'short',day:'numeric'});
}
